## Правила дат (опорная дата = дата звонка, Europe/Minsk)
- День недели («в/до/к пятнице/пятницы/среде»): ближайший БУДУЩИЙ такой день после даты
  звонка. Если совпадает с днём звонка («в пятницу», сказано в пятницу) → через неделю +
  флаг same_weekday_ambiguous. «До пятницы» = включительно эта пятница.
- Число месяца («до двадцатого», «к 15-му», «15 числа»): ближайшее будущее такое число (этот
  месяц, если число > дня звонка, иначе следующий). Равно дню звонка → флаг same_day_of_month.
  Порядковые числительные словами в родительном падеже («двадцатого», «тридцать первого») —
  обязательно поддержать.
- Явные даты «15 октября», «15.10» → ближайшая будущая такая дата.
- сегодня / завтра / послезавтра; «через N дней/недель» (N может быть словом: «через три дня»,
  «через неделю» = +7).
- «на следующей неделе» → интервал пн–вс следующей недели (start=пн, end=вс).
- «на этой неделе» → интервал от дня звонка до вс; если звонок в пт/сб/вс → флаг interval_collapsed.
- «до конца недели» → вс этой недели; «до конца месяца» → последний день месяца.
- «на днях», «в ближайшее время», «как можно скорее», «после праздников» → type vague, флаг vague.
- Срока нет → type none, флаг no_deadline.
- Не распознано → флаг unparsed, сырой текст сохраняется. Праздники РБ не учитываем.

## Проверка цитат
Нормализация (нижний регистр, ё→е, без пунктуации), rapidfuzz.fuzz.partial_ratio по каждому
сегменту, порог ~85; пробовать склейку соседних сегментов. Найдено → speaker и t (= start
сегмента) берутся из расшифровки, match_score записывается. Не найдено → verified=false, в
интерфейсе такое обязательство уходит в свёрнутый блок «Не подтверждено цитатой».

## Интерфейс (Streamlit, app.py)
Выбор клиента; заголовок карточки; колонки «Мы должны» (debtor=employee) и «Нам должны»
(debtor=client), блок «Третьи лица»; карточка обязательства: действие, срок «к среде → ср, 14.10»,
флаги бейджами, сумма, условие, статус, цитата курсивом, st.audio(audio_path, start_time=int(t))
если есть аудио, кнопки ✓ подтвердить / ✎ исправить / ✗ отклонить (сохраняются в store.json).
Намерения (tentative) — в свёрнутом блоке. Блок «Предложено закрыть» с кнопкой «Закрыть».
Блок «Загрузить звонок» (wav + телефон + дата/время → конвейер), если ASR доступен.
Должен работать на mock-данных без LLM и без аудио.

