## Вход и сценарий
- Звук: телефонный, 8 кГц, G.711 (A-law). Предпочтительно ДВУХКАНАЛЬНЫЙ (левый канал —
  сотрудник, правый — клиент): тогда диаризация не нужна, автор каждой фразы известен.
- Источник в продукте — «Виртуальная АТС» МТС (в демо заменяется загрузкой wav-файла).
- Режим: разбор ПОСЛЕ звонка (не реальное время).
- Язык: русский. Белорусский — только дорожная карта, не делать.
- Часовой пояс: Europe/Minsk (UTC+3). Дата звонка — опорная для всех относительных дат.

## Конвейер
wav (стерео) → разделить каналы → ASR по каждому каналу (фразы с временем) → слить по времени →
расшифровка (контракт ниже) → LLM извлекает обязательства по JSON-схеме → КОД: проверка цитат,
время и автор из расшифровки, нормализация дат, флаги → хранилище → интерфейс.
Второй звонок: открытые обязательства клиента + новая расшифровка → LLM предлагает закрытия →
проверка цитат → интерфейс («Предложено закрыть»).

Принцип: модель ПРЕДЛАГАЕТ, детерминированный КОД ПРОВЕРЯЕТ. LLM не считает даты и не
ставит время/автора — это делает код по расшифровке.

## ASR
- Основной: T-one (github.com/voicekit-team/T-one, Apache 2.0, обучен на русской телефонии,
  CTC, ~71M параметров, встроенный разделитель фраз с временем: StreamingCTCPipeline,
  forward_offline). Запускать на КАЖДОМ канале отдельно. Зависимость KenLM собирается из
  исходников — может капризничать.
- Запасной: GigaAM-v3 (github.com/salute-developers/GigaAM, MIT; варианты e2e_ctc / e2e_rnnt;
  .transcribe принимает до 25 с → резать Silero VAD (MIT) на отрезки).
- Диаризацию (pyannote) НЕ делаем: при стерео не нужна. ВАЖНО: pyannote community-1 сам
  сводит стерео в моно — никогда не подавать ему стерео. На телефонном корпусе CALLHOME у него
  26,7% DER — это аргумент за стерео.

## LLM
- Решение команды: продукт НЕ строится на моделях/API Anthropic.
- Доступ к LLM — через OpenAI-совместимый интерфейс (python-пакет openai, base_url/model/api_key
  из .env или config). Тогда локальная модель (Ollama, vLLM, llama.cpp server) и облачные
  API меняются строкой конфига. Предпочтение в продукте — локальная Qwen3 (Apache 2.0).
- Облачных ключей НЕТ. Обязателен mock-бэкенд (детерминированный), чтобы весь конвейер,
  тесты и интерфейс работали без LLM.
- Структурированный вывод: response_format json_schema, если поддерживается; иначе JSON-режим
  + валидация pydantic + один повтор с сообщением об ошибке.
- Промпты — на русском, с 2–3 короткими примерами. Правила в промпте: только явные
  обязательства; статус по формулировке («наверное», «может», «не точно» → tentative);
  «если …» → conditional + condition; замена срока («нет, лучше к среде») → новое обязательство
  с replaces; цитаты ДОСЛОВНЫЕ; срок отдавать разложенным (raw/type/value), не вычислять дату.

