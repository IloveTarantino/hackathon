cat > .night/night_loop.sh <<'EOF_LOOP'
#!/usr/bin/env bash
set -u
cd "$(dirname "$0")/.."
source .night/config.sh
LOG=.night/log.txt
log(){ echo "[$(date '+%F %T')] $*" | tee -a "$LOG"; }
LIMIT_RE='usage limit|limit reached|hit your .{0,20}limit|rate.?limit|resets? (at|in|on) |limit will reset|out of (extra )?usage|429'

stop_epoch=$(date -d "$STOP_AT" +%s)
[ "$stop_epoch" -le "$(date +%s)" ] && stop_epoch=$(date -d "tomorrow $STOP_AT" +%s)
log "Старт цикла. Остановка: $(date -d @"$stop_epoch" '+%F %T'). Модель: ${MODEL:-по умолчанию}"

iter=0; fails=0
while [ "$(date +%s)" -lt "$stop_epoch" ]; do
  iter=$((iter+1))
  if grep -q -- '- \[ \]' TASKS.md; then pf=.night/prompt_task.txt; else pf=.night/prompt_improve.txt; fi
  left=$(( stop_epoch - $(date +%s) ))
  t=$ITER_TIMEOUT; [ "$left" -lt "$t" ] && t=$left
  [ "$t" -lt 60 ] && break
  out=.night/iter_$(printf '%03d' "$iter").txt
  margs=(); [ -n "$MODEL" ] && margs=(--model "$MODEL")
  log "Итерация $iter ($(basename "$pf")), таймаут ${t}с"
  timeout --signal=INT --kill-after=90 "$t" \
    "$CLAUDE_BIN" -p "$(cat "$pf")" --dangerously-skip-permissions ${margs[@]+"${margs[@]}"} \
    > "$out" 2>&1 < /dev/null
  rc=$?
  tailtxt=$(tail -c 1500 "$out")
  log "  rc=$rc, конец вывода: $(echo "$tailtxt" | tail -c 300 | tr '\n' ' ')"

  if echo "$tailtxt" | grep -qiE "$LIMIT_RE" && { [ "$rc" -ne 0 ] || [ "$(wc -c < "$out")" -lt 1500 ]; }; then
    log "  Лимит исчерпан. Жду ${LIMIT_SLEEP}с и пробую снова."
    sleep "$LIMIT_SLEEP"; continue
  fi
  if [ "$rc" -eq 0 ]; then fails=0; sleep 5; continue; fi
  if [ "$rc" -eq 124 ] || [ "$rc" -eq 130 ] || [ "$rc" -eq 137 ]; then
    log "  Итерация упёрлась в таймаут — продолжаю со следующей."; fails=0; continue
  fi
  if [ -n "$MODEL" ] && echo "$tailtxt" | grep -qi 'model' && echo "$tailtxt" | grep -qiE 'not (found|available|supported|allowed)|invalid|does not exist|no access|unknown'; then
    log "  Модель $MODEL недоступна — переключаюсь на модель по умолчанию."; MODEL=""; continue
  fi
  fails=$((fails+1))
  log "  Ошибка (подряд: $fails)."
  if [ -n "$MODEL" ] && [ "$fails" -ge 3 ]; then
    log "  3 ошибки подряд с моделью $MODEL — на всякий случай переключаюсь на модель по умолчанию."; MODEL=""
  fi
  if [ "$fails" -ge 5 ]; then sleep 900; else sleep "$ERROR_SLEEP"; fi
done
log "Время вышло или задачи закончились — цикл остановлен."
EOF_LOOP
chmod +x .night/night_loop.sh

