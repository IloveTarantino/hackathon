def dl(raw=None, type="none", value=None, start=None, end=None, flags=None):
    """Срок. Без аргументов — срока нет."""
    if flags is None:
        flags = {"none": ["no_deadline"], "vague": ["vague"]}.get(type, [])
    return {"raw": raw, "type": type, "value": value, "resolved_start": start,
            "resolved_end": end or start, "flags": flags}


def cm(n, debtor, creditor, action, quotes, deadline=None, status="firm", amount=None,
       condition=None, replaces=None, debtor_name=None):
    return {"n": n, "debtor": debtor, "creditor": creditor, "action": action,
            "quotes": [quotes] if isinstance(quotes, str) else quotes,
            "deadline": deadline or dl(), "status": status, "amount": amount,
            "condition": condition, "replaces": replaces, "debtor_name": debtor_name}


def money(value, raw, approximate=False):
    return {"value": value, "currency": "BYN", "approximate": approximate, "raw": raw}


