def timed_segments(lines):
    """Время фраз: ~2,7 слова в секунду, пауза между репликами 0,3–0,6 с (детерминированно)."""
    t, out = 0.8, []
    for i, (speaker, text) in enumerate(lines):
        dur = round(0.4 + 0.37 * len(text.split()), 1)
        out.append({"speaker": speaker, "start": round(t, 1), "end": round(t + dur, 1),
                    "text": text})
        t += dur + 0.3 + 0.1 * (i % 4)
    return out


def find_evidence(segments, quote, call_id):
    hits = [s for s in segments if quote in s["text"]]
    if len(hits) != 1:
        raise SystemExit(f"{call_id}: цитата должна встречаться ровно в одной фразе "
                         f"(найдено {len(hits)}): {quote!r}")
    return {"speaker": hits[0]["speaker"], "t": hits[0]["start"], "quote": quote,
            "match_score": 100}


def build(call):
    cid = call["call_id"]
    segments = timed_segments(call["segments"])
    transcript = Transcript.model_validate({
        **{k: call[k] for k in ("call_id", "call_datetime", "client_phone", "client_name",
                                "direction")},
        "audio_path": None, "segments": segments})
    commitments = []
    for c in call["commitments"]:
        commitments.append({
            "id": f"{cid}_c{c['n']}", "client_phone": call["client_phone"], "call_id": cid,
            "debtor": c["debtor"], "debtor_name": c["debtor_name"], "creditor": c["creditor"],
            "action": c["action"], "deadline": c["deadline"], "amount": c["amount"],
            "condition": c["condition"], "status": c["status"],
            "replaces": f"{cid}_c{c['replaces']}" if c["replaces"] else None,
            "review": "pending", "lifecycle": "open",
            "evidence": [find_evidence(segments, q, cid) for q in c["quotes"]],
            "verified": True})
    closures = []
    for commitment_id, quote in call.get("closures", []):
        ev = find_evidence(segments, quote, cid)
        closures.append({"commitment_id": commitment_id, "speaker": ev["speaker"],
                         "t": ev["t"], "quote": quote})
    gold = GoldCall.model_validate({"call_id": cid, "commitments": commitments,
                                    "closures": closures})
    return transcript, gold


def main():
    for call in CALLS:
        transcript, gold = build(call)
        dump_model(transcript, ROOT / "data" / "transcripts" / f"{transcript.call_id}.json")
        dump_model(gold, ROOT / "data" / "gold" / f"{gold.call_id}.json")
        print(f"{transcript.call_id}: {len(transcript.segments)} фраз, "
              f"{len(gold.commitments)} обязательств, {len(gold.closures)} закрытий")


if __name__ == "__main__":
    main()
